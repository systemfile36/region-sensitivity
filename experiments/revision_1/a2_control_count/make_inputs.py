#!/usr/bin/env python3
"""Write the A2 inputs that are derived rather than hand-written.

* ``data/revision_1/imagenet/val_2_per_class_a2.txt``: within every class of
  ``data/phase3/imagenet/val_10_per_class.txt``, the two files with the
  lowest ``sha256("rev1-a2:" + filename)`` (2,000 samples).
* ``configs/synthetic_shortcut_k20.yaml``: the synthetic baseline's config as
  built by ``run_threshold_validation_full._build_config``, with
  ``controls[0].n_samples`` set to 20.

With ``--check``, nothing is written; the script fails unless the files on
disk match what it would write and the SHA-256 values registered in
``protocol.json``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml

from experiments.revision_1.common.runs import REPO_ROOT
from experiments.revision_1.common.subsets import class_balanced_subset

A2_DIR = Path(__file__).resolve().parent
PROTOCOL_PATH = A2_DIR / "protocol.json"
SOURCE_ANNOTATION = REPO_ROOT / "data" / "phase3" / "imagenet" / "val_10_per_class.txt"
SUBSET_PATH = REPO_ROOT / "data" / "revision_1" / "imagenet" / "val_2_per_class_a2.txt"
SUBSET_SALT = "rev1-a2"
PER_CLASS = 2
SYNTHETIC_DIR = REPO_ROOT / "experiments" / "synthetic_shortcut"
SYNTHETIC_CONFIG_PATH = A2_DIR / "configs" / "synthetic_shortcut_k20.yaml"
N_CONTROLS = 20


def subset_text() -> str:
    """Return the annotation file content of the A2 subset."""

    lines = class_balanced_subset(SOURCE_ANNOTATION, PER_CLASS, SUBSET_SALT)
    return "".join(f"{filename} {label}\n" for filename, label in lines)


def synthetic_config_text() -> str:
    """Return the synthetic K=20 config as YAML."""

    sys.path.insert(0, str(SYNTHETIC_DIR))
    from run_threshold_validation_full import _build_config  # noqa: PLC0415

    data_dir = SYNTHETIC_DIR / "data"
    channel_mean = json.loads((data_dir / "dataset_stats.json").read_text(encoding="utf-8"))["channel_mean"]
    config = _build_config(
        checkpoint_path=SYNTHETIC_DIR / "checkpoints_crop_free" / "m_shortcut.pt",
        manifest_path=data_dir / "manifests" / "A_audit.json",
        channel_mean=channel_mean,
    )
    config["controls"][0]["n_samples"] = N_CONTROLS
    header = (
        "# Generated by experiments/revision_1/a2_control_count/make_inputs.py from\n"
        "# experiments/synthetic_shortcut/run_threshold_validation_full.py _build_config;\n"
        "# only controls[0].n_samples differs from the synthetic_shortcut baseline (2 -> 20).\n"
    )
    return header + yaml.safe_dump(config, sort_keys=False)


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Verify instead of writing.")
    args = parser.parse_args(argv)

    outputs = {SUBSET_PATH: subset_text(), SYNTHETIC_CONFIG_PATH: synthetic_config_text()}
    if args.check:
        registered = json.loads(PROTOCOL_PATH.read_text(encoding="utf-8"))["inputs_sha256"]
        failures = []
        for path, text in outputs.items():
            key = path.relative_to(REPO_ROOT).as_posix()
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                failures.append(f"{key}: differs from the generated content")
            if registered.get(key) != _sha256(text):
                failures.append(f"{key}: SHA-256 differs from protocol.json")
        for failure in failures:
            print(failure, file=sys.stderr)
        return 1 if failures else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        path.chmod(0o644)
        print(f"{path.relative_to(REPO_ROOT)} sha256={_sha256(text)} lines={text.count(chr(10))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
